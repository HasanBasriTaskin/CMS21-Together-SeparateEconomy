using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using HarmonyLib;
using Hx = HarmonyLib.Harmony;
using MelonLoader;

[assembly: MelonInfo(typeof(TogetherSeparateEconomy.Main), "Together Separate Economy", "1.0.0", "HasanBasriTaskin", "https://github.com/HasanBasriTaskin/CMS21-Together-SeparateEconomy")]
[assembly: MelonGame("Red Dot Games", "Car Mechanic Simulator 2021")]
[assembly: VerifyLoaderVersion(0, 5, 7)]
[assembly: MelonAdditionalDependencies("CMS21-Together")]

namespace TogetherSeparateEconomy
{
    /// <summary>
    /// PART 2 seam: implement this in a new class (public, parameterless ctor) to have its
    /// Harmony patches applied automatically. Each group is applied in its own try/catch.
    /// </summary>
    public interface IPatchGroup
    {
        string Name { get; }
        void Apply(Hx harmony);
    }

    /// <summary>
    /// PART 2 seam: implement this to get Init (after config + patches) and per-frame Update on the main thread.
    /// </summary>
    public interface IModPart
    {
        string Name { get; }
        void Init();
        void Update();
    }

    public class Main : MelonMod
    {
        /// <summary>"1.0.0+" + UTC build time (yyyyMMddHHmmss), generated by the GenBuildStamp MSBuild target.</summary>
        public static readonly string ModVersion = "1.0.0+" + BuildInfo.Stamp;
        public const string Tag = "[TSE] ";

        public static Main Instance;
        public static Hx HarmonyInst;

        /// <summary>False when channel registration failed (packet ID clash): every feature must stay off.</summary>
        public static bool Disabled;

        static readonly Queue<Action> _queue = new Queue<Action>();
        static readonly List<IModPart> _parts = new List<IModPart>();

        /// <summary>Raised every frame on the main thread after the queue was pumped.</summary>
        public static event Action FrameTick;

        /// <summary>True until a "garage" scene loaded or 120 s passed: per-frame startup profile guard.</summary>
        public static bool EarlyGuardActive = true;
        static readonly System.Diagnostics.Stopwatch _sinceStart = System.Diagnostics.Stopwatch.StartNew();

        public override void OnSceneWasLoaded(int buildIndex, string sceneName)
        {
            Log.Debug("Scene loaded: " + sceneName + " (" + buildIndex + ")");
            StartupProfileGuard.CheckFull(true);
            if (string.Equals(sceneName, "garage", StringComparison.OrdinalIgnoreCase)) EarlyGuardActive = false;
        }

        public override void OnSceneWasInitialized(int buildIndex, string sceneName)
        {
            Log.Debug("Scene initialized: " + sceneName + " (" + buildIndex + ")");
            StartupProfileGuard.CheckFull(true);
        }

        public override void OnInitializeMelon()
        {
            Instance = this;
            try { Config.Load(); }
            catch (Exception e) { Log.Error("Config load failed: " + e); }

            StartupProfileGuard.Check();

            HarmonyInst = new Hx("TogetherSeparateEconomy");
            ApplyPatches();

            // Channel registration (also re-done by postfixes whenever Together rebuilds its handler tables).
            try { Net.TryRegisterAll(); }
            catch (Exception e) { Log.Error("Channel registration error: " + e); }

            // IPatchGroup (Filters) and IModPart (Flow) classes are auto-discovered.
            LoadParts();
            Log.Msg("Together Separate Economy " + ModVersion + " loaded. " + Config.Summary());
        }

        static void ApplyPatches()
        {
            var groups = new List<IPatchGroup> { new NetPatches() };
            foreach (var t in Assembly.GetExecutingAssembly().GetTypes())
            {
                if (t.IsAbstract || t.IsInterface || t == typeof(NetPatches)) continue;
                if (!typeof(IPatchGroup).IsAssignableFrom(t)) continue;
                try { groups.Add((IPatchGroup)Activator.CreateInstance(t)); }
                catch (Exception e) { Log.Error("Could not create patch group " + t.Name + ": " + e.Message); }
            }
            foreach (var g in groups)
            {
                try { g.Apply(HarmonyInst); Log.Debug("Patch group applied: " + g.Name); }
                catch (Exception e) { Log.Error("Patch group failed (" + g.Name + "), continuing with the others: " + e); }
            }
        }

        static void LoadParts()
        {
            foreach (var t in Assembly.GetExecutingAssembly().GetTypes())
            {
                if (t.IsAbstract || t.IsInterface || !typeof(IModPart).IsAssignableFrom(t)) continue;
                try
                {
                    var p = (IModPart)Activator.CreateInstance(t);
                    p.Init();
                    _parts.Add(p);
                }
                catch (Exception e) { Log.Error("Could not start part " + t.Name + ": " + e); }
            }
        }

        /// <summary>Run an action on the main thread during the next OnUpdate (thread-safe).</summary>
        public static void Post(Action a)
        {
            if (a == null) return;
            lock (_queue) _queue.Enqueue(a);
        }

        public override void OnApplicationQuit()
        {
            StartupProfileGuard.Check();
            StartupProfileGuard.CheckFull(false);
            try { ClientFlow.OnQuit(); }
            catch (Exception e) { Log.Error("OnApplicationQuit error: " + e.Message); }
        }

        public override void OnUpdate()
        {
            if (EarlyGuardActive)
            {
                if (_sinceStart.Elapsed.TotalSeconds > 120) EarlyGuardActive = false;
                else StartupProfileGuard.CheckFull(true);
            }
            try
            {
                int guard = 0;
                while (guard++ < 500)
                {
                    Action a;
                    lock (_queue)
                    {
                        if (_queue.Count == 0) break;
                        a = _queue.Dequeue();
                    }
                    try { a(); }
                    catch (Exception e) { Log.Error("Main-thread task error: " + e); }
                }
                Net.Tick();
                foreach (var p in _parts)
                {
                    try { p.Update(); }
                    catch (Exception e) { Log.Error("Part Update error (" + p.Name + "): " + e); }
                }
                var h = FrameTick;
                if (h != null)
                {
                    foreach (Action d in h.GetInvocationList())
                    {
                        try { d(); } catch (Exception e) { Log.Error("FrameTick error: " + e); }
                    }
                }
            }
            catch (Exception e) { Log.Error("OnUpdate error: " + e); }
        }
    }

    public static class Log
    {
        public static void Msg(string s) { MelonLogger.Msg(Main.Tag + s); }
        public static void Warn(string s) { MelonLogger.Warning(Main.Tag + s); }
        public static void Error(string s) { MelonLogger.Error(Main.Tag + s); }
        public static void Debug(string s) { if (Config.DebugLog) MelonLogger.Msg(Main.Tag + "[debug] " + s); }
    }
}


